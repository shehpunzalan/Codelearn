// Function to seed demo students into localStorage
export function seedDemoStudents(): void {
  const existingUsers = localStorage.getItem('registeredUsers');
  const registeredUsers = existingUsers ? JSON.parse(existingUsers) : [];
  
  // Only add demo students if there are no existing students
  const hasStudents = registeredUsers.some((u: any) => u.role === 'student');
  
  if (!hasStudents) {
    // Add all demo students
    registeredUsers.push(...demoStudents);
    localStorage.setItem('registeredUsers', JSON.stringify(registeredUsers));
    
    // Also seed their progress data
    seedDemoProgress();
    
    console.log(`✅ Seeded ${demoStudents.length} demo students`);
  }
}

// Function to seed demo progress data for students
function seedDemoProgress(): void {
  demoStudents.forEach((student, index) => {
    const studentId = student.id;
    
    // Determine performance level based on index
    // Exactly 10 students in each category as shown in the image
    // HIGH PERFORMANCE (>70%): First 10 students (0-9)
    // MEDIUM PERFORMANCE (40-70%): Next 10 students (10-19)  
    // LOW PERFORMANCE (<40%): Last 10 students (20-29)
    let performanceLevel: 'high' | 'medium' | 'low';
    if (index < 10) {
      performanceLevel = 'high';
    } else if (index < 20) {
      performanceLevel = 'medium';
    } else {
      performanceLevel = 'low';
    }
    
    // Create progress data
    const progressData = generateProgressData(studentId, performanceLevel, index);
    const submissionsData = generateSubmissionsData(studentId, performanceLevel, index);
    
    // Store in localStorage
    const allProgress = JSON.parse(localStorage.getItem('allProgress') || '[]');
    const allSubmissions = JSON.parse(localStorage.getItem('allSubmissions') || '[]');
    
    allProgress.push(...progressData);
    allSubmissions.push(...submissionsData);
    
    localStorage.setItem('allProgress', JSON.stringify(allProgress));
    localStorage.setItem('allSubmissions', JSON.stringify(allSubmissions));
  });
}

function generateProgressData(userId: string, level: 'high' | 'medium' | 'low', index: number) {
  const progressData = [];
  const totalModules = 10;
  const lessonsPerModule = [11, 12, 10, 13, 11, 12, 10, 11, 13, 12]; // Total = 115
  
  // Specific module completion counts based on performance level (as shown in image)
  let modulesCompleted: number;
  if (level === 'high') {
    // HIGH: 7-10 modules completed
    const highModules = [9, 8, 9, 10, 8, 9, 7, 8, 9, 8];
    modulesCompleted = highModules[index] || 8;
  } else if (level === 'medium') {
    // MEDIUM: 4-6 modules completed
    const mediumModules = [6, 5, 6, 5, 5, 4, 5, 5, 4, 4];
    modulesCompleted = mediumModules[index - 10] || 5;
  } else {
    // LOW: 1-3 modules completed
    const lowModules = [3, 2, 3, 1, 2, 2, 3, 1, 2, 1];
    modulesCompleted = lowModules[index - 20] || 2;
  }
  
  // Complete all lessons in the first N modules
  for (let moduleIdx = 0; moduleIdx < modulesCompleted; moduleIdx++) {
    const moduleLessons = lessonsPerModule[moduleIdx];
    
    for (let lessonIdx = 0; lessonIdx < moduleLessons; lessonIdx++) {
      progressData.push({
        userId,
        moduleId: `mod${moduleIdx + 1}`,
        lessonId: `lesson${lessonIdx + 1}`,
        completed: true,
        lastAccessed: new Date(Date.now() - Math.random() * 7 * 24 * 60 * 60 * 1000).toISOString(),
        timeSpent: 900 + Math.floor(Math.random() * 1800) // 15-45 minutes
      });
    }
  }
  
  return progressData;
}

function generateSubmissionsData(userId: string, level: 'high' | 'medium' | 'low', index: number) {
  const submissionsData = [];
  
  // Score ranges based on performance level (matching image thresholds)
  // HIGH (>70%), MEDIUM (40-70%), LOW (<40%)
  const scoreRanges = {
    high: { min: 75, max: 98 },      // >70% range
    medium: { min: 45, max: 70 },    // 40-70% range  
    low: { min: 20, max: 39 }        // <40% range
  };
  
  const { min, max } = scoreRanges[level];
  
  // Number of submissions based on level (as shown in image)
  let submissionCount: number;
  if (level === 'high') {
    // HIGH: 22-27 submissions
    const highSubmissions = [25, 24, 26, 27, 23, 25, 22, 24, 25, 23];
    submissionCount = highSubmissions[index] || 24;
  } else if (level === 'medium') {
    // MEDIUM: 14-20 submissions
    const mediumSubmissions = [19, 17, 20, 18, 16, 15, 18, 17, 14, 15];
    submissionCount = mediumSubmissions[index - 10] || 17;
  } else {
    // LOW: 5-12 submissions
    const lowSubmissions = [12, 9, 11, 7, 8, 9, 10, 6, 7, 5];
    submissionCount = lowSubmissions[index - 20] || 8;
  }
  
  for (let i = 0; i < submissionCount; i++) {
    const score = min + Math.floor(Math.random() * (max - min));
    
    submissionsData.push({
      id: `submission-${userId}-${i}`,
      userId,
      moduleId: `mod${(i % 10) + 1}`,
      code: `public class Example${i} { /* Student code */ }`,
      score,
      submittedAt: new Date(Date.now() - Math.random() * 14 * 24 * 60 * 60 * 1000).toISOString(),
      feedback: score >= 70 
        ? 'Excellent work! Your code demonstrates strong understanding of OOP principles.'
        : score >= 40
        ? 'Good effort. Consider reviewing encapsulation and inheritance concepts.'
        : 'Needs improvement. Please review the module materials and try again.'
    });
  }
  
  return submissionsData;
}